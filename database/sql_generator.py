"""Runtime SQL generation for the `tasks` table.

This module is the executable counterpart of
`.agents/skills/sql-generation/SKILL.md`. The skill file describes the
contract for a coding agent; this module implements the very same contract
for the FastAPI application:

1. classify the request (done upstream in ``ai/intent_detection.py``),
2. describe the operation as **structured data** (never as free-form SQL
   written by a model),
3. validate that structure against the schema rules,
4. hand the operation to ``database.sql_execution`` for the final SQL
   validation and execution.

The model never gets to choose a table, a column, a task id or a value. It
only fills in the fields it read from the employee's sentence; everything
else is derived here from the ORM model, which is the single source of truth
for the schema (see ``DATABASE_SCHEMA.md``).

Example of a validated operation::

    {
        "intent": "UPDATE_TASK",
        "operation": "UPDATE",
        "table": "tasks",
        "task_id": 12,
        "updates": {"status": "IN_PROGRESS", "progress": 70},
        "sql": "UPDATE tasks SET status = :status, progress = :progress "
               "WHERE id = :task_id AND assigned_to = :assigned_to",
        "params": {"status": "IN_PROGRESS", "progress": 70,
                   "task_id": 12, "assigned_to": "Rahul"},
    }
"""

from __future__ import annotations

from datetime import date, time

from database import search as task_search
from database.models import Task
from database.sql_execution import validate_sql

TASK_TABLE = "tasks"

# The ORM model is the source of truth for the columns.
MODEL_COLUMNS = frozenset(column.name for column in Task.__table__.columns)

# `id` is generated by the database and can never be written by an update.
READABLE_COLUMNS = frozenset(MODEL_COLUMNS)
WRITABLE_COLUMNS = frozenset(MODEL_COLUMNS - {"id"})

STATUS_VALUES = frozenset({"PENDING", "IN_PROGRESS", "COMPLETED"})

DATE_COLUMNS = frozenset(
    {"assigned_date", "deadline_date", "reminder_date"}
)
TIME_COLUMNS = frozenset(
    {"assigned_time", "deadline_time", "reminder_time"}
)
TEXT_COLUMNS = frozenset({"task_title", "assigned_to", "status"})
INTEGER_COLUMNS = frozenset({"progress"})

COLUMN_ORDER = (
    "task_title",
    "assigned_to",
    "assigned_date",
    "assigned_time",
    "deadline_date",
    "deadline_time",
    "reminder_date",
    "reminder_time",
    "status",
    "progress",
)


class OperationError(ValueError):
    """Raised when a structured operation is not valid for the schema."""


def _validate_value(column: str, value):
    """Validate one column value against the schema value rules."""

    if value is None:
        return None

    if column == "status":
        if not isinstance(value, str) or value.upper() not in STATUS_VALUES:
            raise OperationError(
                "status must be PENDING, IN_PROGRESS, or COMPLETED."
            )
        return value.upper()

    if column in INTEGER_COLUMNS:
        if isinstance(value, bool) or not isinstance(value, int):
            raise OperationError(f"{column} must be an integer between 0 and 100.")
        if not 0 <= value <= 100:
            raise OperationError(f"{column} must be between 0 and 100.")
        return value

    if column in DATE_COLUMNS:
        if isinstance(value, date):
            return value
        try:
            return date.fromisoformat(str(value))
        except ValueError as error:
            raise OperationError(
                f"{column} must be a YYYY-MM-DD date."
            ) from error

    if column in TIME_COLUMNS:
        if isinstance(value, time):
            return value
        try:
            parts = str(value).split(":")
            return time(int(parts[0]), int(parts[1]))
        except (ValueError, IndexError) as error:
            raise OperationError(f"{column} must be an HH:MM time.") from error

    if not isinstance(value, str):
        raise OperationError(f"{column} must be text.")

    if column == "task_title" and not value.strip():
        raise OperationError("task_title cannot be empty.")

    return value


def _ordered_updates(updates: dict) -> dict:
    """Return the updates in the canonical column order."""

    ordered = {}
    for column in COLUMN_ORDER:
        if column in updates:
            ordered[column] = updates[column]

    for column in updates:
        if column not in ordered:
            ordered[column] = updates[column]

    return ordered


def validate_updates(updates) -> dict:
    """Validate a mapping of column names to values.

    Unknown columns are rejected, so a model can never invent a column that
    does not exist in the schema.
    """

    if not isinstance(updates, dict):
        raise OperationError("updates must be a mapping of column names to values.")

    if not updates:
        raise OperationError("At least one field must be updated.")

    validated = {}

    for column, value in updates.items():
        if column not in WRITABLE_COLUMNS:
            raise OperationError(f"Unknown column '{column}'.")
        validated[column] = _validate_value(column, value)

    return _ordered_updates(validated)


def _validate_task_id(task_id) -> int:
    if isinstance(task_id, bool) or not isinstance(task_id, int):
        raise OperationError("task_id must be an integer.")
    if task_id <= 0:
        raise OperationError("task_id must be a positive integer.")
    return task_id


def build_update_operation(
    task_id: int,
    updates: dict,
    *,
    intent: str = "UPDATE_TASK",
    owner: str | None = None,
) -> dict:
    """Build the structured UPDATE operation for one task."""

    validated = validate_updates(updates)
    validated_id = _validate_task_id(task_id)

    columns = list(validated)
    assignments = ", ".join(f"{column} = :{column}" for column in columns)

    where = "id = :task_id"
    params = {column: validated[column] for column in columns}
    params["task_id"] = validated_id

    if owner:
        where = f"{where} AND assigned_to = :assigned_to"
        params["assigned_to"] = owner

    sql = (
        f"UPDATE {TASK_TABLE} SET {assignments} WHERE {where} "
        "RETURNING id, task_title, assigned_to, assigned_date, assigned_time, "
        "deadline_date, deadline_time, reminder_date, reminder_time, "
        "status, progress"
    )

    return {
        "intent": intent,
        "operation": "UPDATE",
        "table": TASK_TABLE,
        "task_id": validated_id,
        "owner": owner,
        "updates": validated,
        "sql": sql,
        "params": params,
    }


def build_select_operation(
    *,
    task_id: int | None = None,
    status: str | None = None,
    statuses: list[str] | tuple[str, ...] | None = None,
    assigned_to: str | None = None,
    owner: str | None = None,
    title_contains: str | None = None,
    intent: str = "GET_TASK",
) -> dict:
    """Build the structured SELECT operation used to read tasks.

    ``title_contains`` is split into search concepts, so a multi-word query
    ("research about MCP") becomes several case-insensitive ``ILIKE`` terms
    joined by ``OR``. The caller ranks the returned rows by relevance.

    ``owner`` is an exact ownership scope (case-insensitive); it is separate
    from the partial ``assigned_to`` filter.
    """

    conditions = []
    params: dict = {}

    if task_id is not None:
        conditions.append("id = :task_id")
        params["task_id"] = _validate_task_id(task_id)

    if statuses:
        normalized_statuses = []

        for value in statuses:
            if not isinstance(value, str) or value.upper() not in STATUS_VALUES:
                raise OperationError(
                    "status must be PENDING, IN_PROGRESS, or COMPLETED."
                )
            if value.upper() not in normalized_statuses:
                normalized_statuses.append(value.upper())

        if normalized_statuses:
            keys = []
            for index, value in enumerate(normalized_statuses):
                key = f"status_{index}"
                keys.append(f":{key}")
                params[key] = value
            conditions.append("status IN (" + ", ".join(keys) + ")")

    elif status is not None:
        if status.upper() not in STATUS_VALUES:
            raise OperationError(
                "status must be PENDING, IN_PROGRESS, or COMPLETED."
            )
        conditions.append("status = :status")
        params["status"] = status.upper()

    if assigned_to:
        conditions.append("assigned_to ILIKE :assigned_to")
        params["assigned_to"] = f"%{assigned_to.strip()}%"

    if owner:
        conditions.append("assigned_to ILIKE :owner")
        params["owner"] = owner.strip()

    if title_contains:
        terms = task_search.sql_terms(title_contains)

        if terms:
            likes = []
            for index, term in enumerate(terms):
                key = f"title_{index}"
                likes.append(f"task_title ILIKE :{key}")
                params[key] = f"%{term}%"

            conditions.append("(" + " OR ".join(likes) + ")")
        else:
            conditions.append("task_title ILIKE :title_contains")
            params["title_contains"] = f"%{title_contains.strip()}%"

    sql = (
        "SELECT id, task_title, assigned_to, assigned_date, assigned_time, "
        "deadline_date, deadline_time, reminder_date, reminder_time, "
        "status, progress FROM tasks"
    )

    if conditions:
        sql = f"{sql} WHERE " + " AND ".join(conditions)

    sql = f"{sql} ORDER BY id"

    return {
        "intent": intent,
        "operation": "SELECT",
        "table": TASK_TABLE,
        "task_id": task_id,
        "status": status.upper() if status else None,
        "statuses": list(statuses or []) or None,
        "assigned_to": assigned_to,
        "owner": owner,
        "title_contains": title_contains,
        "sql": sql,
        "params": params,
    }


def build_delete_operation(
    task_id: int,
    *,
    intent: str = "DELETE_TASK",
    owner: str | None = None,
) -> dict:
    """Build the structured DELETE operation for one task."""

    validated_id = _validate_task_id(task_id)

    where = "id = :task_id"
    params: dict = {"task_id": validated_id}

    if owner:
        where = f"{where} AND assigned_to = :assigned_to"
        params["assigned_to"] = owner

    sql = (
        f"DELETE FROM {TASK_TABLE} WHERE {where} "
        "RETURNING id, task_title, assigned_to, status, progress"
    )

    return {
        "intent": intent,
        "operation": "DELETE",
        "table": TASK_TABLE,
        "task_id": validated_id,
        "owner": owner,
        "sql": sql,
        "params": params,
    }


def build_insert_operation(values: dict, *, intent: str = "CREATE_TASK") -> dict:
    """Build the structured INSERT operation used to create a task."""

    validated = validate_updates(values)

    columns = list(validated)
    placeholders = ", ".join(f":{column}" for column in columns)

    sql = (
        f"INSERT INTO {TASK_TABLE} ({', '.join(columns)}) "
        f"VALUES ({placeholders}) RETURNING id"
    )

    return {
        "intent": intent,
        "operation": "INSERT",
        "table": TASK_TABLE,
        "task_id": None,
        "updates": validated,
        "sql": sql,
        "params": {column: validated[column] for column in columns},
    }


def validate_operation(operation: dict) -> dict:
    """Validate a structured operation before anything touches the database.

    Returns the operation when it is valid, raises ``OperationError``
    otherwise. The SQL text itself is re-validated with the shared execution
    layer, so the generated statement is checked against the same rules an
    agent-written statement would face.
    """

    if not isinstance(operation, dict):
        raise OperationError("The operation must be a JSON object.")

    operation_type = operation.get("operation")
    if operation_type not in {"SELECT", "INSERT", "UPDATE", "DELETE"}:
        raise OperationError("Unsupported operation.")

    if operation.get("table") != TASK_TABLE:
        raise OperationError("Only the tasks table may be referenced.")

    if operation_type == "UPDATE":
        task_id = operation.get("task_id")
        if task_id is None:
            raise OperationError("An UPDATE requires a task id.")
        _validate_task_id(task_id)
        validate_updates(operation.get("updates") or {})
    elif operation_type == "DELETE":
        if operation.get("task_id") is None:
            raise OperationError("A DELETE requires a task id.")
        _validate_task_id(operation["task_id"])
    elif operation_type == "INSERT":
        validate_updates(operation.get("updates") or {})

    sql = operation.get("sql")
    validation = validate_sql(sql)
    if not validation.allowed:
        raise OperationError(validation.reason or "The generated SQL is not allowed.")

    if validation.operation != operation_type:
        raise OperationError("The SQL statement does not match the operation.")

    return operation


def to_sql_request(operation: dict, *, confirmation: str | None = None) -> dict:
    """Convert a validated operation into a ``run_sql_request`` payload."""

    validated = validate_operation(operation)

    return {
        "operation": validated["operation"],
        "sql": validated["sql"],
        "params": validated.get("params") or {},
        "confirmation": confirmation,
    }
